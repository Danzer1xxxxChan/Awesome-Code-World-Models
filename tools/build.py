def bibtex(records):
 out=['% Generated from data/papers.json. Dates refer to first arXiv posting where known.\n']
 def clean(s):return s.replace('\\','').replace('{','').replace('}','').replace('&',r'\&').replace('%',r'\%')
 for r in records:
  fields={'title':'{'+clean(r['title'])+'}','url':r['links'].get('paper',r['verification']['source']),'urldate':'2026-10-22'}
  if r['authors']:fields['author']=' and '.join(clean(x) for x in r['authors'])
  if r.get('year'):fields['year']=str(r['year'])
  if r.get('arxiv_id'):fields.update(eprint=r['arxiv_id'],archivePrefix='arXiv')
  out.append('@misc{cwm_'+r['id'].lower()+',\n'+',\n'.join('  '+k+' = {'+v+'}' for k,v in fields.items())+'\n}\n')
 return '\n'.join(out)

